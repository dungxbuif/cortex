from __future__ import annotations

from typing import Protocol

from ai_service.core.models import CaptureStatus


class Embedder(Protocol):
    def embed_text(self, text: str) -> tuple[float, ...]:
        """Return an embedding vector for one text value."""

    def embed_batch(self, texts: list[str]) -> list[tuple[float, ...]]:
        """Return embedding vectors in the same order as the input texts."""


class SecondBrainRepository(Protocol):
    def save_capture(self, capture): ...
    def list_captures(self, owner_id: str): ...
    def get_capture(self, owner_id: str, capture_id: str): ...
    def update_capture_status(self, owner_id: str, capture_id: str, status: CaptureStatus, updated_at, vault_path=None): ...
    def get_document(self, owner_id: str, vault_path: str): ...
    def upsert_document_with_chunks(self, document, chunks: list): ...
    def delete_document(self, owner_id: str, vault_path: str): ...
    def save_ingestion_job(self, job): ...
    def get_ingestion_job(self, owner_id: str, job_id: str): ...
    def update_ingestion_job_status(self, owner_id: str, job_id: str, status: str, message: str, attempts: int): ...
    def list_searchable_chunks(self, owner_id: str, include_archive: bool = False): ...
    def sync_status(self, owner_id: str): ...


class HomelabRepository(Protocol):
    def get_homelab_document(self, owner_id: str, file_path: str): ...
    def upsert_homelab_document_with_chunks(self, document, chunks: list): ...
    def list_searchable_homelab_chunks(self, owner_id: str): ...
    def sync_homelab_status(self, owner_id: str): ...
